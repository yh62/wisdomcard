// ======= 카드 이미지 preloade =======
const CARD_IMAGES = 80; // 이미지 개수 (80장)
const preloadedImages = [];
for(let i = 0; i < CARD_IMAGES; i++){
    const img = new Image();
    img.src = `./assets/images/${i}.jpg`;
    preloadedImages.push(img);
}

// ======= 카드 뽑기 =======
const mainElm = document.querySelector('main');
const cardImg = document.querySelector('.card-img');
const cardText = document.querySelector('.card-text');
const cardBtn = document.querySelector('.card-btn');
function reloadCard(){
    if(mainElm.dataset.state == 'loading') return;
    
    mainElm.dataset.state = 'loading';
    cardBtn.classList.add('opacity-5');

    const imgIndex = Math.floor(Math.random() * CARD_IMAGES);
    const textIndex = Math.floor(Math.random() * data.length);
    setTimeout(() => {
        cardImg.src = `./assets/images/${imgIndex}.jpg`;
        cardText.textContent = data[textIndex];

        mainElm.dataset.state = 'card';
        cardBtn.classList.remove('opacity-5');
    }, 1500);
}

// 이벤트 적용 (클릭 & 키보드)
cardBtn.onclick = reloadCard;
window.onkeydown = (e) => {
  if(e.code === 'Space'){
    e.preventDefault(); 
    reloadCard();
  }
}

// ======= modal =======
const modal = document.querySelector('.modal');
const modalContents = document.querySelectorAll('.modal-content');
const openModalBtns = document.querySelectorAll('.open-modal-btn');
const closeModalbtn = document.querySelector('.close-modal-btn');

// open
openModalBtns.forEach((btn) => {
    btn.onclick = (e) => {
        document.body.classList.add('overflow-hidden');
        document.getElementById(e.target.dataset.content).style.display = 'block';
        modal.style.display = 'block';
        modal.style.animation = 'fade-in 370ms forwards';
    }
});

// close
closeModalbtn.onclick = (e) => {
    modal.addEventListener("animationend", () => { 
        document.body.classList.remove('overflow-hidden');
        modalContents.forEach((elm) => { elm.style.display = 'none'; });
        modal.style.display = 'none';
    }, { once: true });
    modal.style.animation = 'fade-out 370ms forwards';
}

